#!/usr/bin/env node
/** Real pointer navigation; unlike screenshot parity, never normalize scrolling after a click. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { acceptanceLaunchOptions, closeAcceptanceBrowser } from '../../scripts/acceptance-config.mjs';
import { readOfficialPluginCatalog } from './official-plugin-catalog-oracle.mjs';
import { readOwnedPluginInventory } from './owned-plugin-inventory-oracle.mjs';
import { managerCopy } from './plugin-manager-assertions.mjs';
import { settle } from './stability.mjs';
import { navigationObservation, scrollToNavigationTarget, assertNavigationTop } from './plugin-navigation-assertions.mjs';
const app = resolve(import.meta.dirname, '../..');
const require = createRequire(resolve(app, 'package.json'));
const puppeteer = require('puppeteer-core');
const vite = await import(require.resolve('vite'));
const configFile = resolve(app, 'vite.parity.config.ts');
const output = resolve(app, 'dist/parity-evidence/plugin-navigation');
const official = readOfficialPluginCatalog(), owned = readOwnedPluginInventory();
const bundle = 'dsh-base:ai-chat-core';
const expectedComponents = owned.bundles.find(row => row.name === bundle).rows.length;
let server, browser;
const cases = [];
try {
  await mkdir(output, { recursive: true });
  await vite.build({ configFile, logLevel: 'error' });
  server = await vite.preview({ configFile, logLevel: 'error', preview: { host: '127.0.0.1', port: 0, strictPort: true } });
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
  browser = await puppeteer.launch(acceptanceLaunchOptions());
  for (const locale of ['en', 'zh']) for (const width of [1280, 720]) for (const side of ['reference', 'adapted']) {
    const page = await browser.newPage(), errors = [];
    page.setDefaultTimeout(15000);
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewport({ width, height: 900, deviceScaleFactor: 1 });
    await page.evaluateOnNewDocument(({ official, owned }) => { window.__PLUGIN_CATALOG_REFERENCE__ = official; window.__OWNED_PLUGIN_REFERENCE__ = owned; }, { official: official.bundles, owned });
    await page.goto(`${origin}/?${new URLSearchParams({ surface: 'plugin-manager', state: 'navigation', side, locale })}`, { waitUntil: 'networkidle0' });
    await page.waitForFunction(() => window.__PLUGIN_PARITY__?.source.getSnapshot().status === 'ready');
    await page.evaluate(() => { document.body.setAttribute('data-ds-dark-theme', ''); });
    const selector = `[data-plugin-package="${bundle}"] button[aria-describedby]`;
    await scrollToNavigationTarget(page, selector);
    const list = await navigationObservation(page);
    assert.ok(list.scrollTop > 0, 'navigation starts from a scrolled list');
    const label = `${locale}-${width}-${side}`;
    await page.screenshot({ path: resolve(output, `${label}-list.png`), captureBeyondViewport: false });
    await page.click(selector);
    await page.waitForSelector(`[data-plugin-detail="${bundle}"]`);
    await settle(page);
    const detail = await navigationObservation(page, { detailSelector: `[data-plugin-detail="${bundle}"]`, backLabel: managerCopy(locale).backToList });
    assert.equal(detail.rowCount, expectedComponents, 'both renderers receive the complete real AI chat composition');
    await page.screenshot({ path: resolve(output, `${label}-detail.png`), captureBeyondViewport: false });
    const transitions = [];
    if (side === 'reference') {
      assert.ok(detail.scrollTop > 0, 'pinned official renderer retains the reproduced navigation defect');
      assert.equal(detail.back.visible, false, 'official reference does not expose the back button on entry');
    } else {
      assertNavigationTop(detail);
      const record = async (name, options = {}, extra = {}) => {
        await settle(page);
        const observation = await navigationObservation(page, options);
        assertNavigationTop(observation, extra);
        transitions.push({ name, ...observation });
        return observation;
      };
      const backToList = async selector => {
        await page.click(`${selector} button[aria-label=${JSON.stringify(managerCopy(locale).backToList)}]`);
        await page.waitForSelector('[data-plugin-group="bundles"]');
        return record('back-to-main', {}, { back: false, list: true });
      };
      await page.$eval('[data-plugin-body]', body => { body.scrollTop = 500; body.dispatchEvent(new Event('scroll')); });
      await settle(page);
      const beforeRefresh = await navigationObservation(page);
      assert.ok(beforeRefresh.scrollTop > 0);
      await page.evaluate(() => window.__PLUGIN_PARITY__.refresh());
      await page.waitForFunction(() => window.__PLUGIN_PARITY__.source.getSnapshot().refreshStatus !== 'refreshing');
      await settle(page);
      const afterRefresh = await navigationObservation(page);
      assert.equal(afterRefresh.scrollTop, beforeRefresh.scrollTop, 'same-detail refresh keeps the reading position');
      transitions.push({ name: 'same-view-refresh', before: beforeRefresh.scrollTop, after: afterRefresh.scrollTop });
      await page.setViewport({ width: width - 40, height: 900, deviceScaleFactor: 1 });
      await settle(page);
      const resized = await navigationObservation(page);
      assert.ok(resized.scrollTop > 0, 'same-detail resize does not reset to the top');
      assert.equal(resized.readingAnchor?.row, afterRefresh.readingAnchor?.row, 'native wrapping preserves the first visible component across resize');
      await page.setViewport({ width, height: 900, deviceScaleFactor: 1 });
      await settle(page);
      transitions.push({ name: 'same-view-resize', before: afterRefresh.scrollTop, after: resized.scrollTop, beforeAnchor: afterRefresh.readingAnchor, afterAnchor: resized.readingAnchor });
      const rowSelector = '[data-plugin-row="client:session-adapter"] button:not([role="switch"])';
      await scrollToNavigationTarget(page, rowSelector);
      await page.click(rowSelector);
      const rowDetail = '[data-plugin-row-detail]';
      await page.waitForSelector(rowDetail);
      const rowBack = managerCopy(locale).backToPackage.replace('{name}', detail.title.text);
      await record('row-configuration', { detailSelector: rowDetail, backLabel: rowBack });
      await page.$eval('[data-plugin-body]', body => { body.scrollTop = 200; body.dispatchEvent(new Event('scroll')); });
      await page.click(`${rowDetail} button[aria-label=${JSON.stringify(rowBack)}]`);
      await page.waitForSelector(`[data-plugin-detail="${bundle}"]`);
      await record('row-back-to-package', { detailSelector: `[data-plugin-detail="${bundle}"]`, backLabel: managerCopy(locale).backToList });
      await backToList('[data-plugin-detail]');
      const itemSelector = '[data-plugin-item="shell"] button';
      await scrollToNavigationTarget(page, itemSelector);
      await page.click(itemSelector);
      await page.waitForSelector('[data-plugin-item-detail="shell"]');
      await record('builtin-configuration', { detailSelector: '[data-plugin-item-detail="shell"]', backLabel: managerCopy(locale).backToList });
      await page.$eval('[data-plugin-body]', body => { body.scrollTop = 200; body.dispatchEvent(new Event('scroll')); });
      await backToList('[data-plugin-item-detail]');
      const moreSelector = '[data-plugin-group="extensions"] > div button';
      await scrollToNavigationTarget(page, moreSelector);
      await page.click(moreSelector);
      await page.waitForSelector('[data-plugin-group="more"]');
      await record('main-to-more', { backLabel: managerCopy(locale).backToList });
      const lastPackage = official.more.at(-1), lastSelector = `[data-plugin-package="${lastPackage}"] button[aria-describedby]`;
      await scrollToNavigationTarget(page, lastSelector);
      const moreBefore = await navigationObservation(page);
      assert.ok(moreBefore.scrollTop > 0);
      await page.click(lastSelector);
      const lastDetail = `[data-plugin-detail="${lastPackage}"]`;
      await page.waitForSelector(lastDetail);
      const moreBack = managerCopy(locale).backToPackage.replace('{name}', managerCopy(locale).moreTitle);
      await record('more-to-package', { detailSelector: lastDetail, backLabel: moreBack });
      await page.click(`${lastDetail} button[aria-label=${JSON.stringify(moreBack)}]`);
      await page.waitForSelector('[data-plugin-group="more"]');
      await record('package-back-to-more', { backLabel: managerCopy(locale).backToList });
      await page.click(`button[aria-label=${JSON.stringify(managerCopy(locale).backToList)}]`);
      await page.waitForSelector('[data-plugin-group="bundles"]');
      await record('more-back-to-main', {}, { back: false, list: true });
      const writes = await page.evaluate(() => window.__PLUGIN_PARITY__.requests.filter(request => request.method !== 'GET'));
      assert.deepEqual(writes, [], 'navigation and refresh never write plugin controls');
    }
    assert.deepEqual(errors, []);
    cases.push({ locale, width, side, list, detail, transitions, errors });
    console.log(`[plugin-navigation] ${label}: list=${list.scrollTop} detail=${detail.scrollTop} titleVisible=${detail.title.visible} backVisible=${detail.back.visible}, ${transitions.length} transition checks`);
    await page.close();
  }
  await writeFile(resolve(output, 'report.json'), JSON.stringify({ ok: true, scope: 'Pinned official Page retains the reproduced defect; adapted navigation resets new logical views before paint, preserves same-view refresh/resize, and restores list header visibility. Actual own AI chat composition and official configuration slots, pointer clicks, no post-click normalization.', cases }, null, 2));
} finally { await closeAcceptanceBrowser(browser); await server?.close(); }
