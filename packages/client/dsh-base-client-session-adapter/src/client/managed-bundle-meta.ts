type PluginMeta = NonNullable<BundleInfo['meta']>;
type PluginBrand = 'Dsh-base' | 'Cloudflare';

/** Product branding identifies an integration, not the package author or runtime origin. */
function brandedTitle(title: string, brand: PluginBrand): string {
  return title.startsWith(`${brand} `) ? title : `${brand} ${title}`;
}

/** Own copy follows the pinned DSH metadata: a branded name and one concrete purpose. */
function meta(en: string, zh: string, descriptionEn: string, descriptionZh: string, brand: PluginBrand = 'Dsh-base'): PluginMeta {
  return {
    title: { en: brandedTitle(en, brand), zh: brandedTitle(zh, brand) },
    description: { en: descriptionEn, zh: descriptionZh },
    ...(brand === 'Cloudflare' ? { icon: CLOUDFLARE_PLUGIN_ICON } : {}),
  };
}

