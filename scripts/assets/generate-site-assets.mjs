#!/usr/bin/env node
/** Regenerate the site's committed assets from the pinned official FishLogo.
 * Run with --check for a read-only provenance, byte/hash and generated-table check.
 * --check-rendered additionally regenerates every file in memory with Chromium.
 */
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { acceptanceLaunchOptions, closeAcceptanceBrowser } from '../../apps/web/scripts/acceptance-config.mjs';
import { repoRoot } from '../conformance/lib.mjs';
import { buildContext, cliProductRoot, generatedPath } from '../build/product-paths.mjs';
import { readOfficialSiteMark, sha256 } from './official-site-mark.mjs';

const productRoot = cliProductRoot();
const require = createRequire(join(buildContext(productRoot).appRoot, 'package.json'));
const publicDir = generatedPath(productRoot, 'apps/web/public');
const provenancePath = generatedPath(productRoot, 'scripts/assets/site-assets.provenance.json');
const versionsPath = generatedPath(productRoot, 'packages/boot/dsh-base-site-seo/src/assets.generated.ts');
export const ASSET_SIZES = Object.freeze({
  '/favicon.svg': [512, 512], '/favicon-dark.svg': [512, 512], '/favicon.ico': [48, 48],
  '/favicon-16x16.png': [16, 16], '/favicon-32x32.png': [32, 32],
  '/apple-touch-icon.png': [180, 180], '/icon-192.png': [192, 192],
  '/icon-512.png': [512, 512], '/icon-maskable-512.png': [512, 512], '/og.png': [1200, 630],
});
export const DESIGN = Object.freeze({ background: '#171717', foreground: '#ffffff', websiteLight: '#000000', websiteDark: '#ffffff', websiteFallback: '#000000', iconWidth: 448, maskableWidth: 320, safeCircleRadius: 204.8, cornerRadius: 112, ogLogoWidth: 192 });
export const DARK_VARIANTS = Object.freeze({ '/favicon.svg': '/favicon-dark.svg' });

export function makeSvg(mark, dark = false) {
  const height = DESIGN.iconWidth * mark.viewBox.height / mark.viewBox.width;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="dsh-base"><svg x="${(512 - DESIGN.iconWidth) / 2}" y="${(512 - height) / 2}" width="${DESIGN.iconWidth}" height="${height}" viewBox="0 0 ${mark.viewBox.width} ${mark.viewBox.height}"><path d="${mark.path}" fill="${dark ? DESIGN.websiteDark : DESIGN.websiteLight}"/></svg></svg>\n`;
}

/** ICO contains the exact lossless 16/32/48 PNGs, not browser-dependent BMP conversion. */
export function makeIco(images) {
  const directory = Buffer.alloc(6 + images.length * 16);
  directory.writeUInt16LE(1, 2); directory.writeUInt16LE(images.length, 4);
  let offset = directory.length;
  images.forEach(({ size, bytes }, index) => {
    const at = 6 + index * 16;
    directory[at] = size; directory[at + 1] = size;
    directory.writeUInt16LE(1, at + 4); directory.writeUInt16LE(32, at + 6);
    directory.writeUInt32LE(bytes.length, at + 8); directory.writeUInt32LE(offset, at + 12);
    offset += bytes.length;
  });
  return Buffer.concat([directory, ...images.map(image => image.bytes)]);
}

export function pngSize(bytes) {
  assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a', 'PNG signature');
  assert.equal(bytes.subarray(12, 16).toString(), 'IHDR');
  return [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
}

export function icoFrames(bytes) {
  assert.equal(bytes.readUInt16LE(0), 0); assert.equal(bytes.readUInt16LE(2), 1);
  assert.equal(bytes.readUInt16LE(4), 3, 'ICO must carry 16/32/48 frames');
  return [16, 32, 48].map((size, index) => {
    const at = 6 + index * 16;
    assert.equal(bytes[at], size); assert.equal(bytes[at + 1], size);
    assert.equal(bytes.readUInt16LE(at + 4), 1); assert.equal(bytes.readUInt16LE(at + 6), 32);
    const offset = bytes.readUInt32LE(at + 12), length = bytes.readUInt32LE(at + 8);
    assert.ok(offset >= 54 && offset + length <= bytes.length, 'ICO frame must be inside the file');
    const image = bytes.subarray(offset, offset + length);
    assert.deepEqual(pngSize(image), [size, size]);
    return { size, bytes: image };
  });
}

export function versionModule(assets, source) {
  const versions = Object.fromEntries(Object.entries(assets).map(([path, asset]) => [path, asset.sha256.slice(0, 12)]));
  return `/** Generated by scripts/assets/generate-site-assets.mjs; do not edit.\n * Official FishLogo: ${source.package} stable root exports, ${source.commit}.\n * Exact file hashes and source provenance: scripts/assets/site-assets.provenance.json.\n */\nexport const SITE_ASSET_VERSIONS: Readonly<Record<string, string>> = ${JSON.stringify(versions, null, 2)};\n\n/** Media variants belong only to these exact bundled website favicon paths. */\nexport const SITE_ASSET_DARK_VARIANTS: Readonly<Record<string, string>> = ${JSON.stringify(DARK_VARIANTS, null, 2)};\n`;
}

export async function renderSiteAssets(mark) {
  const puppeteer = require('puppeteer-core');
  let browser;
  try {
    const launch = acceptanceLaunchOptions();
    browser = await puppeteer.launch({ ...launch, args: [...launch.args, '--disable-gpu'] });
    const page = await browser.newPage();
    const data = await page.evaluate(async ({ path, viewBox, fonts, design }) => {
      for (const [name, weight] of [['regular', '400'], ['medium', '500']]) {
        const font = new FontFace('DSH Site Asset', `url(data:font/woff2;base64,${fonts[name]})`, { weight });
        document.fonts.add(await font.load());
      }
      const shape = new Path2D(path);
      const canvas = (width, height) => { const el = document.createElement('canvas'); el.width = width; el.height = height; return { el, ctx: el.getContext('2d', { alpha: true }) }; };
      const markAt = (ctx, x, y, width, color = design.foreground) => {
        ctx.save(); ctx.translate(x, y); ctx.scale(width / viewBox.width, width / viewBox.width);
        ctx.fillStyle = color; ctx.fill(shape); ctx.restore();
      };
      const icon = (size, maskable = false) => {
        const { el, ctx } = canvas(size, size); const scale = size / 512;
        ctx.scale(scale, scale); ctx.fillStyle = design.background;
        if (maskable) ctx.fillRect(0, 0, 512, 512);
        else { ctx.beginPath(); ctx.roundRect(0, 0, 512, 512, design.cornerRadius); ctx.fill(); }
        const width = maskable ? design.maskableWidth : design.iconWidth;
        markAt(ctx, (512 - width) / 2, (512 - width * viewBox.height / viewBox.width) / 2, width);
        return el.toDataURL('image/png').split(',')[1];
      };
      const result = Object.fromEntries([180, 192, 512].map(size => [String(size), icon(size)]));
      result.maskable = icon(512, true);
      // Website fallbacks retain the official default black silhouette and
      // transparent background. The document's SVG links select theme variants.
      for (const size of [16, 32, 48]) {
        const { el, ctx } = canvas(size, size); ctx.scale(size / 512, size / 512);
        const width = design.iconWidth;
        markAt(ctx, (512 - width) / 2, (512 - width * viewBox.height / viewBox.width) / 2, width, design.websiteFallback);
        result[`favicon${size}`] = el.toDataURL('image/png').split(',')[1];
      }
      const { el, ctx } = canvas(1200, 630);
      ctx.fillStyle = design.background; ctx.fillRect(0, 0, 1200, 630);
      markAt(ctx, 96, 315 - design.ogLogoWidth * viewBox.height / viewBox.width / 2, design.ogLogoWidth);
      ctx.textBaseline = 'top'; ctx.fillStyle = design.foreground; ctx.font = '500 84px "DSH Site Asset"'; ctx.fillText('dsh-base', 344, 214);
      ctx.fillStyle = '#c7c7c7'; ctx.font = '400 30px "DSH Site Asset"'; ctx.fillText('DeepSeek Harness Base', 346, 330);
      ctx.fillStyle = '#a0a0a0'; ctx.fillText('DSH on Cloudflare Workers', 346, 386);
      ctx.fillStyle = '#383838'; ctx.fillRect(96, 470, 1008, 2);
      ctx.fillStyle = '#a0a0a0'; ctx.font = '500 26px "DSH Site Asset"'; ctx.fillText('dsh-base', 96, 500);
      result.og = el.toDataURL('image/png').split(',')[1];
      return result;
    }, { path: mark.path, viewBox: mark.viewBox, fonts: mark.fonts, design: DESIGN });
    const png = key => Buffer.from(data[key], 'base64');
    const files = {
      '/favicon.svg': Buffer.from(makeSvg(mark)), '/favicon-dark.svg': Buffer.from(makeSvg(mark, true)), '/favicon.ico': makeIco([16, 32, 48].map(size => ({ size, bytes: png(`favicon${size}`) }))),
      '/favicon-16x16.png': png('favicon16'), '/favicon-32x32.png': png('favicon32'), '/apple-touch-icon.png': png(180),
      '/icon-192.png': png(192), '/icon-512.png': png(512), '/icon-maskable-512.png': png('maskable'), '/og.png': png('og'),
    };
    return { files, renderer: { browser: await browser.version(), method: 'Canvas2D Path2D, uniform scale, pinned Montserrat fonts', ico: 'lossless PNG frames: 16,32,48' } };
  } finally { await closeAcceptanceBrowser(browser); }
}

export function checkSiteAssets() {
  const mark = readOfficialSiteMark(productRoot);
  const provenance = JSON.parse(readFileSync(provenancePath, 'utf8'));
  assert.equal(provenance.schemaVersion, 1);
  assert.deepEqual(provenance.source, mark.source, 'official pin/export/source drift: review and regenerate assets');
  assert.deepEqual(provenance.geometry, { pathSha256: sha256(mark.path), viewBox: mark.viewBox, ...DESIGN });
  assert.deepEqual(Object.keys(provenance.assets), Object.keys(ASSET_SIZES));
  assert.equal(readFileSync(join(publicDir, 'favicon.svg'), 'utf8'), makeSvg(mark), 'SVG must contain the exact exported official whale');
  assert.equal(readFileSync(join(publicDir, 'favicon-dark.svg'), 'utf8'), makeSvg(mark, true), 'dark SVG must contain the same exported official whale');
  for (const [path, size] of Object.entries(ASSET_SIZES)) {
    const bytes = readFileSync(join(publicDir, path.slice(1)));
    assert.equal(sha256(bytes), provenance.assets[path].sha256, `${path}: stale asset bytes`);
    assert.deepEqual([provenance.assets[path].width, provenance.assets[path].height], size, `${path}: declared dimensions`);
    assert.equal(bytes.length, provenance.assets[path].bytes, `${path}: byte length`);
    if (path.endsWith('.png')) assert.deepEqual(pngSize(bytes), size, `${path}: real PNG dimensions`);
    if (path.endsWith('.ico')) icoFrames(bytes);
  }
  assert.equal(readFileSync(versionsPath, 'utf8'), versionModule(provenance.assets, provenance.source), 'asset URL versions must match every committed file');
  return { mark, provenance };
}

async function main() {
  const args = process.argv.slice(2).filter((arg, index, all) => arg !== '--root' && all[index - 1] !== '--root');
  assert.ok(args.every(arg => ['--check', '--check-rendered'].includes(arg)), 'Usage: node scripts/assets/generate-site-assets.mjs [--check | --check-rendered]');
  if (args.length) {
    const { mark } = checkSiteAssets();
    if (args.includes('--check-rendered')) {
      const { files } = await renderSiteAssets(mark);
      for (const [path, bytes] of Object.entries(files)) assert.ok(bytes.equals(readFileSync(join(publicDir, path.slice(1)))), `${path}: rendered output changed; review browser/font source and regenerate`);
    }
    console.log(`site-assets: ${Object.keys(ASSET_SIZES).length} official whale assets, source provenance and URL versions verified${args.includes('--check-rendered') ? ' (full rendered bytes)' : ''}`);
    return;
  }
  const mark = readOfficialSiteMark(productRoot);
  const { files, renderer } = await renderSiteAssets(mark);
  for (const directory of [publicDir, resolve(provenancePath, '..'), resolve(versionsPath, '..')]) mkdirSync(directory, { recursive: true });
  const assets = {};
  for (const [path, bytes] of Object.entries(files)) {
    writeFileSync(join(publicDir, path.slice(1)), bytes);
    assets[path] = { sha256: sha256(bytes), bytes: bytes.length, width: ASSET_SIZES[path][0], height: ASSET_SIZES[path][1] };
  }
  const provenance = { schemaVersion: 1, source: mark.source, geometry: { pathSha256: sha256(mark.path), viewBox: mark.viewBox, ...DESIGN }, renderer, assets };
  writeFileSync(provenancePath, JSON.stringify(provenance, null, 2) + '\n');
  writeFileSync(versionsPath, versionModule(assets, mark.source));
  console.log(`site-assets: generated ${Object.keys(ASSET_SIZES).length} official whale assets, provenance and URL versions`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
