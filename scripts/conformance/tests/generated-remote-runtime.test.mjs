/** Bundle the actual pinned-generator output with the production resolver. */
import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { repoRoot } from '../lib.mjs';
import { dshSource } from '../../../apps/web/vite.config.ts';

const app = createRequire(join(repoRoot, 'apps/web/package.json'));
const { build } = await import(pathToFileURL(app.resolve('vite')).href);

test('official generated Remote runtime bundles dependencies and executes its real strict codecs', async () => {
  const generatedPath = join(repoRoot, '.artifacts/typecheck/remote/dsh-api-remote-access/remote.js');
  const original = readFileSync(generatedPath, 'utf8');
  assert.match(original, /Generated by @deepseek-ai\/dsh-typert-generator/);
  const entry = join(repoRoot, '.artifacts/generated-runtime-test-entry.js');
  const result = await build({
    configFile: false, root: join(repoRoot, 'apps/web'), logLevel: 'silent',
    plugins: [{ name: 'generated-runtime-entry', resolveId(id) { return id === entry ? entry : null; }, load(id) {
      return id === entry ? "export { default } from '@deepseek-ai/dsh-api-remote-access/remote';" : null;
    } }, dshSource()],
    build: { write: false, minify: false, lib: { entry, formats: ['es'] } },
  });
  const outputs = Array.isArray(result) ? result.flatMap(build => build.output) : result.output;
  const chunks = outputs.filter(output => output.type === 'chunk');
  assert.equal(chunks.length, 1);
  assert.deepEqual(chunks[0].imports, [], 'runtime dependencies must be bundled, never externalized');
  assert.deepEqual(chunks[0].dynamicImports, []);
  assert.equal(readFileSync(generatedPath, 'utf8'), original, 'the generated official module remains unchanged');
  const { default: contribution } = await import(`data:text/javascript;base64,${Buffer.from(chunks[0].code).toString('base64')}`);
  assert.equal(contribution.package, '@deepseek-ai/dsh-api-remote-access');
  const method = contribution.methods['remoteAccess/follow'];
  assert.equal(method.mode, 'stream');
  const schema = method.result.create();
  assert.deepEqual(schema.parse({ type: 'baseline', owner: true }), { type: 'baseline', owner: true });
  assert.throws(() => schema.parse({ type: 'baseline', owner: 'true' }), 'malformed authority must not become an owner grant');
});
