/**
 * Generate the Worker plugin composition from each Worker package's `dshBase.worker`
 * metadata. The app keeps no hand-written Worker roster: run this before cf build.
 */
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { readWorkerRows } from "./packs.mjs";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const output = join(repoRoot, "apps", "web", "src", "worker", "generated-composition.ts");

const rows = readWorkerRows(repoRoot);
rows.sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
const ids = new Set();
for (const row of rows) {
  if (ids.has(row.id)) throw new Error(`duplicate worker composition id: ${row.id}`);
  ids.add(row.id);
}

const lines = [
  "/* Generated by scripts/composition/generate-worker-composition.mjs; do not edit. */",
  'import { StaticPluginEntryId, type StaticPluginLoaderConfig } from "@dsh-base/plugin-loader-static";',
  ...rows.map((row, index) => `import * as plugin${index} from ${JSON.stringify(row.module)};`),
  "",
  "export const workerComposition: StaticPluginLoaderConfig = {",
  "  entries: [",
  ...rows.map((row) => `    { id: StaticPluginEntryId(${JSON.stringify(row.id)}), name: ${JSON.stringify(row.name)}, origin: ${JSON.stringify(row.origin)} as const, disabled: false },`),
  "  ],",
  "  modules: {",
  ...rows.map((row, index) => `    ${JSON.stringify(row.name)}: { load: async () => plugin${index} },`),
  "  },",
  "};",
  "",
];
writeFileSync(output, lines.join("\n"));
console.log(`worker composition: ${rows.length} entries → ${output}`);
