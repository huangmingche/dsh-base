#!/usr/bin/env node
import { buildContext, cliProductRoot, outputPath } from "../build/product-paths.mjs";
/** Extract display data only from the pinned official bundle catalog/resources. */
import { readFileSync, readdirSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { extname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { registerOfficialSourceHooks } from '../build/official-source-hook.mjs';
import { isMain, isPackageExported, officialPackages, repoRoot } from '../conformance/lib.mjs';

export const catalogTarget = 'packages/client/dsh-base-client-session-adapter/src/client/official-bundle-catalog.generated.ts';
const mime = { '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };

/** The exported manifest's icon field is a resource declaration, not a JS import.
 * This is the public readPluginMeta contract documented by @deepseek-ai/dsh-app-boot:
 * a manifest-relative image stays inside its package and is embedded as data.
 * Bundle JavaScript, patches, providers, and app-boot runtime are never evaluated.
 */
function manifestIcon(directory, manifest) {
  if (typeof manifest.icon !== 'string' || isAbsolute(manifest.icon) || /^[A-Za-z][A-Za-z\d+.-]*:/u.test(manifest.icon)) throw new Error(`${manifest.name}: missing/invalid declared icon`);
  const file = realpathSync(resolve(directory, manifest.icon));
  const local = relative(realpathSync(directory), file);
  if (local === '..' || local.startsWith(`..${sep}`) || isAbsolute(local)) throw new Error(`${manifest.name}: icon escapes the declaring package`);
  const mediaType = mime[extname(file).toLowerCase()];
  const stat = statSync(file);
  if (!mediaType || !stat.isFile() || stat.size > 256 * 1024) throw new Error(`${manifest.name}: invalid declared icon resource`);
  return `data:${mediaType};base64,${readFileSync(file).toString('base64')}`;
}

export async function loadOfficialBundleCatalog(root = repoRoot) {
  // The stable entry is data only: installation-owned name lists and the
  // pre-generated on-demand catalog. No optional bundle entry is imported.
  registerOfficialSourceHooks(root);
  const { OPTIONAL_BUNDLES, ON_DEMAND_BUNDLES, OFFICIAL_ON_DEMAND_CATALOG } = await import('@deepseek-ai/dsh-official-bundles');
  const lock = JSON.parse(readFileSync(join(buildContext(root).baseRoot, 'dsh-source.lock.json'), 'utf8'));
  const packages = officialPackages(root);
  const entries = OPTIONAL_BUNDLES.map(name => {
    const entry = packages.get(name);
    if (!entry || !isPackageExported(entry.manifest, './package.json')) throw new Error(`${name}: exported manifest is required`);
    const { manifest, directoryPath } = entry;
    const title = {}, description = {};
    for (const localeFile of readdirSync(join(directoryPath, 'locale')).filter(file => file.endsWith('.json')).sort()) {
      if (!isPackageExported(manifest, `./locale/${localeFile}`)) throw new Error(`${name}: unexported locale ${localeFile}`);
      const locale = localeFile.slice(0, -5);
      const value = JSON.parse(readFileSync(join(directoryPath, 'locale', localeFile), 'utf8')).meta;
      if (typeof value?.title !== 'string' || typeof value?.description !== 'string') throw new Error(`${name}/${localeFile}: display metadata is required`);
      title[locale] = value.title;
      description[locale] = value.description;
    }
    if (!title.en || !title.zh) throw new Error(`${name}: English and Chinese metadata are required`);
    return {
      name, source: 'optional',
      originalListedByDefault: manifest.dsh?.bundle?.listedByDefault ?? true,
      ...(manifest.dsh?.bundle?.platforms === undefined ? {} : { platforms: manifest.dsh.bundle.platforms }),
      metadataSource: `${name}/package.json + ${name}/locale/*.json`,
      iconSource: `${name}/package.json#icon (${manifest.icon})`,
      meta: { title, description, icon: manifestIcon(directoryPath, manifest) },
    };
  });
  for (const name of ON_DEMAND_BUNDLES) {
    const entry = OFFICIAL_ON_DEMAND_CATALOG.find(candidate => candidate.packageName === name);
    if (!entry) throw new Error(`${name}: official on-demand display metadata is required`);
    entries.push({ name, source: 'on-demand', originalListedByDefault: entry.listedByDefault ?? true,
      ...(entry.platforms === undefined ? {} : { platforms: entry.platforms }),
      metadataSource: '@deepseek-ai/dsh-official-bundles#OFFICIAL_ON_DEMAND_CATALOG',
      iconSource: '@deepseek-ai/dsh-official-bundles#OFFICIAL_ON_DEMAND_CATALOG', meta: entry.meta });
  }
  if (new Set(entries.map(row => row.name)).size !== entries.length) throw new Error('duplicate official bundle catalog entry');
  const source = [
    '/* Generated by scripts/composition/generate-official-bundle-catalog.mjs; do not edit. */',
    `/* Official display resources only, pinned commit ${lock.commit}. No bundle runtime is included. */`,
    `export const OFFICIAL_BUNDLE_CATALOG_COMMIT = ${JSON.stringify(lock.commit)};`,
    `export const OFFICIAL_BUNDLE_CATALOG = ${JSON.stringify(entries, null, 2)} as const;`, '',
  ].join('\n');
  return { entries, source, commit: lock.commit };
}

if (isMain(import.meta.url)) {
  const root = cliProductRoot();
  const { entries, source } = await loadOfficialBundleCatalog(root);
  const target = outputPath(root, catalogTarget);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch { /* Missing is stale. */ }
    if (current !== source) { console.error('official bundle catalog is stale: run node scripts/composition/generate-official-bundle-catalog.mjs'); process.exitCode = 1; }
    else console.log(`official bundle catalog: ${entries.length} pinned metadata-only entries verified`);
  } else {
    writeFileSync(target, source);
    console.log(`official bundle catalog: ${entries.length} pinned metadata-only entries generated`);
  }
}
