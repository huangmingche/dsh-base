#!/usr/bin/env node
import { cliProductRoot, outputPath } from "../build/product-paths.mjs";
/**
 * Generate the manageable-module allowlists from every `toggleable: L1` pack.
 * The pack manifests are the single source; the policy module imports the
 * generated constants and never hard-codes a capability list.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readPackManifests } from "./packs.mjs";

const repoRoot = cliProductRoot();
const output = outputPath(repoRoot, "packages/boot/dsh-base-plugin-management/src/manageable.generated.ts");
const check = process.argv.includes("--check");
const packs = readPackManifests(repoRoot);
const l1 = packs.filter(pack => pack.toggleable === "L1");
const nameOf = entry => typeof entry === "string" ? entry : entry.name;
const client = l1.flatMap(pack => (pack.planes.client ?? []).map(nameOf));
const think = l1.flatMap(pack => (pack.planes.think ?? []).map(nameOf));
const worker = l1.flatMap(pack => (pack.planes.worker ?? []).map(nameOf));
if (worker.length > 0 && client.length === 0 && think.length === 0) throw new Error("L1 Worker-only packs are not supported by the current control surface");
const source = [
  "/* Generated by scripts/composition/generate-manageable-composition.mjs; do not edit. */",
  `/* Source: ${l1.map(pack => pack.id).join(", ") || "no L1 packs"}. */`,
  `export const OPTIONAL_CLIENT_MODULES = ${JSON.stringify(client, null, 2)} as const;`,
  `export const OPTIONAL_THINK_MODULES = ${JSON.stringify(think, null, 2)} as const;`,
  `export const OPTIONAL_MANAGEMENT_PACKS = ${JSON.stringify(Object.fromEntries(l1.map(pack => [pack.id, {
    client: (pack.planes.client ?? []).map(nameOf),
    think: (pack.planes.think ?? []).map(nameOf),
  }])), null, 2)} as const;`,
  "",
].join("\n");
if (check) {
  let current = "";
  try { current = readFileSync(output, "utf8"); } catch { /* missing is stale */ }
  if (current !== source) {
    console.error("manageable composition is stale: run node scripts/composition/generate-manageable-composition.mjs");
    process.exitCode = 1;
  } else {
    console.log(`manageable composition: ${client.length} client + ${think.length} think modules from ${l1.length} L1 pack(s)`);
  }
} else {
  writeFileSync(output, source);
  console.log(`manageable composition: ${client.length} client + ${think.length} think modules from ${l1.length} L1 pack(s) → ${output}`);
}
