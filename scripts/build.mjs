#!/usr/bin/env node
/** Bundle the client entry and the Worker; official packages resolve from the pinned rc.5 source. */
import { build } from "esbuild";
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, ".submodules/deepseek-harness");
const official = new Map();

function scan(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) { scan(path); continue; }
    if (entry.name !== "package.json") continue;
    try {
      const manifest = JSON.parse(readFileSync(path, "utf8"));
      if (manifest.name?.startsWith("@deepseek-ai/")) official.set(manifest.name, dirname(path));
    } catch { /* not a package manifest we can use */ }
  }
}
for (const group of ["packages", "vendor"]) {
  const directory = join(source, group);
  if (existsSync(directory)) scan(directory);
}

function resolveOfficial(specifier) {
  const name = specifier.startsWith("@") ? specifier.split("/").slice(0, 2).join("/") : specifier.split("/")[0];
  const directory = official.get(name);
  if (directory === undefined) throw new Error(`rc.5 has no official package: ${specifier}`);
  const sub = specifier.slice(name.length).replace(/^\//u, "");
  const base = sub === "" ? join(directory, "src", "index") : join(directory, "src", sub);
  for (const candidate of [base, `${base}.ts`, `${base}.tsx`, join(base, "index.ts"), join(base, "index.tsx")]) {
    if (existsSync(candidate)) return resolve(candidate);
  }
  throw new Error(`official source is not exported at src/: ${specifier}`);
}

const officialSource = {
  name: "rc5-official-source",
  setup(builder) {
    builder.onResolve({ filter: /^@deepseek-ai\// }, (args) => ({ path: resolveOfficial(args.path) }));
  },
};

mkdirSync(join(root, "dist/assets"), { recursive: true });
await build({
  entryPoints: [join(root, "apps/web/src/client/main.ts")],
  outfile: join(root, "dist/assets/client.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  logLevel: "warning",
});
const client = readFileSync(join(root, "dist/assets/client.js"), "utf8");
writeFileSync(join(root, "apps/web/src/generated-client.ts"),
  `/** Generated by scripts/build.mjs from apps/web/src/client/main.ts — do not edit. */\nexport const clientScript = ${JSON.stringify(client)};\n`);

await build({
  entryPoints: [join(root, "apps/web/src/worker.ts")],
  outfile: join(root, "dist/worker.js"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2024",
  plugins: [officialSource],
  logLevel: "warning",
});
console.log("built dist/worker.js and dist/assets/client.js");
